/**
 * Write the two generated halves of the export module, so `tsc -b` can pass.
 *
 *   node workflow/export/build-deck-css.mjs
 *
 * `src/export/slideModule.tsx` imports two files that git ignores because they
 * are generated per deck:
 *
 *   src/export/deckCss.ts      the compiled Tailwind stylesheet, as a string.
 *                              Written here, every run. Tailwind only emits the
 *                              classes the deck's own source uses, so it is per
 *                              deck and has to be rebuilt when the deck changes.
 *   src/export/revealSteps.ts  build steps per slide. MEASURED against a running
 *                              deck by `build-reveal-steps.mjs`, so this script
 *                              never overwrites it. When it is missing it writes
 *                              an empty placeholder and says so.
 *
 * Nothing generated `deckCss.ts` before this script existed, so a fresh copy of
 * the template failed its own type check, and so did `build:html`, which runs
 * `tsc -b` first. The Authorization deck (Rules_beta/Output/authorization) was
 * the first to hit it and shipped with a hand-written stub.
 *
 * `package.json` runs this before `typecheck`, `build` and `build:html`.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execSync } from 'node:child_process'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '../..')
const EXPORT = path.join(ROOT, 'src/export')
const TMP = path.join(ROOT, 'node_modules', '.deck-export')

fs.mkdirSync(TMP, { recursive: true })

/* ── deckCss.ts, rebuilt every run ────────────────────────────────────── */
const cssOut = path.join(TMP, 'deck.css')
execSync(`npx tailwindcss -i "${path.join(ROOT, 'src/index.css')}" -o "${cssOut}" --minify`, {
  cwd: ROOT,
  stdio: 'pipe',
})
const css = fs.readFileSync(cssOut, 'utf8')
fs.writeFileSync(
  path.join(EXPORT, 'deckCss.ts'),
  `/**
 * The deck's compiled stylesheet, injected by the export module.
 *
 * GENERATED by workflow/export/build-deck-css.mjs. Do not edit.
 */
export const DECK_CSS: string = ${JSON.stringify(css)}
`,
)
console.log(`wrote src/export/deckCss.ts (${Math.round(css.length / 1024)} KB)`)

/* ── revealSteps.ts, only when missing ────────────────────────────────── */
const steps = path.join(EXPORT, 'revealSteps.ts')
if (!fs.existsSync(steps)) {
  fs.writeFileSync(
    steps,
    `/**
 * PLACEHOLDER, not measured. Every slide reads as zero build steps.
 *
 * Measure the real numbers against the running deck, once the slide count is final:
 *
 *   node workflow/export/build-reveal-steps.mjs http://localhost:<devPort> <slideCount>
 */
export const PAGE_REVEAL_MAX_STEPS: number[] = []
`,
  )
  console.log('wrote a PLACEHOLDER src/export/revealSteps.ts: run build-reveal-steps.mjs before shipping')
}
