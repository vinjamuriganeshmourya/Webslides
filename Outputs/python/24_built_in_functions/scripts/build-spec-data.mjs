// Writes src/decks/figures/spec.ts from the pedagogy team's session spec, so
// every program, output, trace step, caption, option and why line on a slide
// is the spec's own text (spec rule 6: "Copy code and outputs from the JSON,
// never retype them"). Re-run after the spec changes:
//   node scripts/build-spec-data.mjs "../../../Reference ppt's/24_built_in_functions_session_spec 1(new).json"
import { readFileSync, writeFileSync } from 'node:fs'
const src = process.argv[2] ?? "../../../Reference ppt's/24_built_in_functions_session_spec 1(new).json"
const spec = JSON.parse(readFileSync(src, 'utf8'))
const cards = {}
for (const b of spec.beats) for (const c of b.cards) {
  const { presses, ...rest } = c // the presses' screen/say prose is for the team, not the slide
  cards[c.id] = rest
}
const out = `/* GENERATED by scripts/build-spec-data.mjs from ${src.split('/').pop()}. Do not edit. */
/* eslint-disable */
export const SPEC: Record<string, any> = ${JSON.stringify(cards, null, 1)}
`
writeFileSync('src/decks/figures/spec.ts', out)
console.log(Object.keys(cards).length, 'cards ->', 'src/decks/figures/spec.ts')
