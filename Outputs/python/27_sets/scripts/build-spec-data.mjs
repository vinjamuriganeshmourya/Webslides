// Writes src/decks/figures/spec.ts from the pedagogy team's session spec, so
// every program, output, trace step, caption, option and why line on a slide
// is the spec's own text (spec rule 6: "Copy code and outputs from the JSON,
// never retype them"). Re-run after the spec changes:
//   node scripts/build-spec-data.mjs "../../../Reference ppt's/27_sets_session_spec.json"
// 2026-10-09: the change spec "27 Sets: add what a data structure is" adds
// DS2 and DS3 and changes C1's press-1 say line. Its JSON is kept beside the
// plan (`../session_plans/27_sets/change_ds.json`) and merged here, so a
// re-run keeps them. A third argument points at another change file.
import { readFileSync, writeFileSync } from 'node:fs'
const src = process.argv[2] ?? "../../../Reference ppt's/27_sets_session_spec.json"
const spec = JSON.parse(readFileSync(src, 'utf8'))
const changeSrc = process.argv[3] ?? '../session_plans/27_sets/change_ds.json'
const change = JSON.parse(readFileSync(changeSrc, 'utf8'))
/* each new card goes into the beat of the card the change spec names, right after it */
for (const c of change.cards) {
  const bi = spec.beats.findIndex((b) => b.cards.some((x) => x.id === change.after[c.id]))
  if (bi < 0) throw new Error(`no card ${change.after[c.id]} to put ${c.id} after`)
  const beat = spec.beats[bi]
  const ci = beat.cards.findIndex((x) => x.id === change.after[c.id])
  beat.cards.splice(ci + 1, 0, c)
}
/* changed lines: only the ones the change spec lists, checked against what they were */
for (const [id, ch] of Object.entries(change.changed)) {
  const card = spec.beats.flatMap((b) => b.cards).find((x) => x.id === id)
  const press = card.presses[ch.press - 1]
  if (press[ch.field] !== ch.was) throw new Error(`${id} press ${ch.press} ${ch.field} is not what the change spec says it was`)
  press[ch.field] = ch.now
}
const cards = {}
const notes = {}
for (const b of spec.beats) for (const c of b.cards) {
  const { presses, ...rest } = c // the presses' screen prose is for the team, not the slide
  cards[c.id] = rest
  /* the speaker notes: each press's say line, and what the room does, in order */
  if (Array.isArray(presses) && presses.length)
    notes[c.id] = presses.map((p, i) => `${presses.length > 1 ? `Press ${i + 1}: ` : ''}${p.say ?? ''}${p.room ? ` (Room: ${p.room})` : ''}`).join(' ')
}
const out = `/* GENERATED by scripts/build-spec-data.mjs from ${src.split('/').pop()} + ${changeSrc.split('/').pop()}. Do not edit. */
/* eslint-disable */
export const SPEC: Record<string, any> = ${JSON.stringify(cards, null, 1)}
export const NOTES: Record<string, string> = ${JSON.stringify(notes, null, 1)}
`
writeFileSync('src/decks/figures/spec.ts', out)
console.log(Object.keys(cards).length, 'cards ->', 'src/decks/figures/spec.ts')
