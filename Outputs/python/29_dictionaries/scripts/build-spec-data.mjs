// Writes src/decks/figures/spec.ts from the pedagogy team's session spec, so
// every program, output, walk step, caption, option, round and why line on a
// slide is the spec's own text (spec rule 6: "Copy code and outputs from the
// JSON, never retype them"). Re-run after the spec changes:
//   node scripts/build-spec-data.mjs "../../../Reference ppt's/29_dictionaries_session_spec.json"
// Session 29's spec already carries DS2 and DS3 (the data structure recall
// cards that sessions 27 and 28 took from a change spec), so there is no
// change file to merge. A second argument may point at one later: it is
// merged the way sessions 27 and 28 did it (`new_beats`, `minutes`,
// `replace`, `set`), and a third at a fixes file.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
const src = process.argv[2] ?? "../../../Reference ppt's/29_dictionaries_session_spec.json"
const spec = JSON.parse(readFileSync(src, 'utf8'))
const merged = [src.split('/').pop()]

/* an optional change file beside the plan: new beats after a named beat, changed minutes */
const changeSrc = process.argv[3] ?? '../session_plans/29_dictionaries/change_ds.json'
if (existsSync(changeSrc)) {
  const change = JSON.parse(readFileSync(changeSrc, 'utf8'))
  for (const nb of change.new_beats ?? []) {
    const bi = spec.beats.findIndex((b) => b.name === nb.after_beat)
    if (bi < 0) throw new Error(`no beat ${nb.after_beat} to put ${nb.name} after`)
    const cards = nb.cards.map((id) => change.cards.find((c) => c.id === id))
    spec.beats.splice(bi + 1, 0, { name: nb.name, kind: nb.kind, mins: nb.mins, cards })
  }
  for (const [name, m] of Object.entries(change.minutes ?? {})) {
    const beat = spec.beats.find((b) => b.name === name)
    if (!beat || beat.mins !== m.was) throw new Error(`beat ${name} is not ${m.was} minutes`)
    beat.mins = m.now
  }
  merged.push(changeSrc.split('/').pop())
}
let start = 0
for (const b of spec.beats) { b.start = start; start += b.mins }
if (start !== 75) throw new Error(`the beats add up to ${start} minutes, not 75`)

/* an optional fixes file: `replace` swaps a whole card, `set` writes one value at a path inside a card */
const fixesSrc = process.argv[4] ?? '../session_plans/29_dictionaries/change_fixes.json'
const allCards = () => spec.beats.flatMap((b) => b.cards)
if (existsSync(fixesSrc)) {
  const fixes = JSON.parse(readFileSync(fixesSrc, 'utf8'))
  for (const [id, card] of Object.entries(fixes.replace ?? {})) {
    const beat = spec.beats.find((b) => b.cards.some((c) => c.id === id))
    if (!beat) throw new Error(`no card ${id} to replace`)
    beat.cards.splice(beat.cards.findIndex((c) => c.id === id), 1, card)
  }
  const setPath = (obj, path, value) => {
    const keys = path.match(/[^.[\]]+|\[\d+\]/g).map((k) => (k.startsWith('[') ? Number(k.slice(1, -1)) : k))
    let at = obj
    for (const k of keys.slice(0, -1)) {
      if (at[k] === undefined) at[k] = typeof keys[keys.indexOf(k) + 1] === 'number' ? [] : {}
      at = at[k]
    }
    at[keys[keys.length - 1]] = value
  }
  for (const [id, edits] of Object.entries(fixes.set ?? {})) {
    const card = allCards().find((c) => c.id === id)
    if (!card) throw new Error(`no card ${id} to change`)
    for (const [path, value] of edits) setPath(card, path, value)
  }
  merged.push(fixesSrc.split('/').pop())
}

const cards = {}
const notes = {}
for (const b of spec.beats) for (const c of b.cards) {
  const { presses, ...rest } = c // the presses' screen prose is for the team, not the slide
  cards[c.id] = rest
  /* the speaker notes: each press's say line, and what the room does, in order */
  if (Array.isArray(presses) && presses.length)
    notes[c.id] = presses.map((p, i) => `${presses.length > 1 ? `Press ${i + 1}: ` : ''}${p.say ?? ''}${p.room ? ` (Room: ${p.room})` : ''}`).join(' ')
}
const out = `/* GENERATED by scripts/build-spec-data.mjs from ${merged.join(' + ')}. Do not edit. */
/* eslint-disable */
export const SPEC: Record<string, any> = ${JSON.stringify(cards, null, 1)}
export const NOTES: Record<string, string> = ${JSON.stringify(notes, null, 1)}
`
writeFileSync('src/decks/figures/spec.ts', out)
console.log(Object.keys(cards).length, 'cards ->', 'src/decks/figures/spec.ts')
