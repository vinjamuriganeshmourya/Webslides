/* Not a check: a report. Writes review/audit.md with the timing numbers of
 * every action, so a reviewer reads one table instead of five hundred keys. */
import { describe, it } from 'vitest'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ACTIONS } from '@/actions'
import type { Channel } from '@/rig/channels'
import { sample, series, peakSpeedTime, REST } from './helpers'

function mainChannel(name: string): Channel {
  const action = ACTIONS[name]
  let best: Channel = 'headNod', dep = -1
  const table = sample(action, 60)
  for (const ch of Object.keys(action.tracks) as Channel[]) {
    const v = series(table, ch)
    const scale = ['shoulderL', 'shoulderR', 'elbowL', 'elbowR', 'wristL', 'wristR', 'headTilt', 'lean'].includes(ch) ? 90 : ['bodyY', 'bodyX', 'headY', 'twist'].includes(ch) ? 40 : 1
    const d = Math.max(...v.map((x) => Math.abs(x - REST[ch]))) / scale
    if (d > dep) { dep = d; best = ch }
  }
  return best
}

describe('audit', () => {
  it('writes review/audit.md', () => {
    const rows: string[] = ['| action | s | loop | channels | keys | main | wind-up | shoulder>elbow>wrist | longest hold | fastest frame |', '|---|---|---|---|---|---|---|---|---|---|']
    for (const [name, action] of Object.entries(ACTIONS)) {
      const table = sample(action, 60)
      const chans = Object.keys(action.tracks) as Channel[]
      const keys = chans.map((c) => action.tracks[c]!.length)
      const main = mainChannel(name)
      const v = series(table, main).map((x) => x - REST[main])
      let peak = 0
      for (const x of v) if (Math.abs(x) > Math.abs(peak)) peak = x
      const early = v.filter((_, i) => table.t[i] <= 0.25)
      const windup = Math.min(...early.map((x) => x * Math.sign(peak)))
      const side = main.endsWith('L') ? 'L' : 'R'
      const arm = chans.includes(`shoulder${side}` as Channel) && chans.includes(`elbow${side}` as Channel)
      const order = arm
        ? [`shoulder${side}`, `elbow${side}`, `wrist${side}`]
            .filter((c) => chans.includes(c as Channel))
            .map((c) => `${c[0]}${peakSpeedTime(table, c as Channel, 0, action.duration * 0.4).toFixed(2)}`)
            .join(' ')
        : ''
      /* longest hold: the longest run of frames where every channel moves under a hair */
      let hold = 0, run = 0
      for (let i = 1; i < table.t.length; i++) {
        const still = chans.every((c) => Math.abs((table.rows[i][c] ?? 0) - (table.rows[i - 1][c] ?? 0)) < 0.002)
        run = still ? run + 1 / 60 : 0
        hold = Math.max(hold, run)
      }
      let fastest = { ch: '', d: 0, t: 0 }
      for (const c of chans) {
        const s = series(table, c)
        for (let i = 1; i < s.length; i++) {
          const d = Math.abs(s[i] - s[i - 1])
          if (d > fastest.d) fastest = { ch: c, d, t: table.t[i] }
        }
      }
      rows.push(
        `| ${name} | ${action.duration.toFixed(2)} | ${action.loop ? 'yes' : ''} | ${chans.length} | ${Math.min(...keys)}..${Math.max(...keys)} | ${main} | ${windup < -0.5 ? 'yes' : 'no'} (${windup.toFixed(2)}) | ${order} | ${hold.toFixed(2)} s | ${fastest.ch} ${fastest.d.toFixed(2)} @ ${fastest.t.toFixed(2)} |`,
      )
    }
    const dir = join(__dirname, '../review')
    mkdirSync(dir, { recursive: true })
    writeFileSync(join(dir, 'audit.md'), `# Action timing audit\n\nGenerated by tests/audit.test.ts. Wind-up: the main channel moves against its own direction in the first 250 ms. Order: time of peak speed per joint in the reach phase. Longest hold: the longest frozen stretch (a hold should still breathe). Fastest frame: the biggest single-frame change at 60 fps.\n\n${rows.join('\n')}\n`)
  })
})
