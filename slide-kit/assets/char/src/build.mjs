// Builds character.svg, rig.json and char.bundle.js.   node src/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { W, H, CX, GROUND, PALETTE, Defs, G, bones, ident, mirror, E } from './lib.mjs';
import { materials, leg, arm, pelvisShapes, torso } from './body.mjs';
import { head } from './head.mjs';

const OUT = path.resolve(import.meta.dirname, '..');
const D = new Defs();
materials(D);

const spine = torso(D, { neck: head(D), armR: arm(D, 'r'), armL: arm(D, 'l') });
const pelvis = G('pelvis', [CX, 712], [pelvisShapes(D), '<!-- right leg (screen left) -->', leg(D, 'r'), '<!-- left leg (screen right) -->', leg(D, 'l'), spine]);
const root = G('root', [CX, GROUND], [pelvis]);
const shadow = s => E([s === 'r' ? 411 : 651, GROUND + 3], 76, 9, 0, '#' + D.soft('ground', 0.85, 0.6), ident, { id: `ground-shadow-${s}`, style: `transform-origin:${s === 'r' ? 411 : 651}px ${GROUND + 3}px` });

const body = [shadow('r'), shadow('l'), ...root];
const used = new Set();
for (const m of [...body, ...D.xml()].join('\n').matchAll(/class="([^"]+)"/g)) m[1].split(' ').forEach(c => used.add(c));
const css = [
  '#character {', ...Object.entries(PALETTE).map(([k, v]) => `  --${k}: ${v};`), '}',
  '#character [data-pivot], #character [id^="ground-shadow"] { transform-box: view-box; }',
  '#character .ln { fill: none; stroke-linecap: round; stroke-linejoin: round; }',
  ...Object.keys(PALETTE).flatMap(k => [
    used.has(`f-${k}`) ? `#character .f-${k} { fill: var(--${k}); }` : null,
    used.has(`s-${k}`) ? `#character .s-${k} { stop-color: var(--${k}); }` : null,
    used.has(`k-${k}`) ? `#character .k-${k} { stroke: var(--${k}); }` : null,
  ]).filter(Boolean),
];
const unusedVars = Object.keys(PALETTE).filter(k => !['f', 's', 'k'].some(p => used.has(`${p}-${k}`)));
if (unusedVars.length) console.log('palette entries never used:', unusedVars.join(', '));

export const svg = [
  `<svg id="character" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" overflow="visible">`,
  '  <title>Rigged 2D character, front view, soft 3D shading</title>',
  '  <style>', ...css.map(l => '    ' + l), '  </style>',
  '  <defs>', ...D.xml().map(l => '    ' + l), '  </defs>',
  ...body.map(l => '  ' + l),
  '</svg>', '',
].join('\n');

// bone table in document order, parent from nesting
const byId = Object.fromEntries(bones.map(b => [b.id, b]));
export const boneList = [];
{
  const stack = [];
  for (const line of svg.split('\n')) {
    const s = line.trim();
    if (s.startsWith('<g')) {
      const m = s.match(/^<g id="([^"]+)" data-pivot/);
      if (m) { boneList.push({ id: m[1], parent: [...stack].reverse().find(Boolean) ?? null, pivot: byId[m[1]].pivot }); stack.push(m[1]); }
      else stack.push(null);
    } else if (s === '</g>') stack.pop();
  }
}

import { rigData } from './rigdef.mjs';
import { readme } from './readme.mjs';
export const rig = rigData(boneList);

// the file shows the default pose on its own: bake each bone's default transform into its style
function bakeDefaults(text) {
  const ch = {};
  const add = (bone, c, v) => { (ch[bone] ??= { r: 0, x: 0, y: 0, sx: 0, sy: 0 })[c] += v; };
  const val = Object.fromEntries(rig.joints.map(j => [j.id, j.default]));
  for (const j of rig.joints) for (const t of j.targets) if (j.default) add(t.bone, t.ch, j.default * t.k);
  for (const f of rig.folds) add(f.bone, 'r', f.k * val[f.flex] * Math.cos(val[f.twist] * Math.PI / 180));
  const r2 = v => Math.round(v * 100) / 100;
  for (const [bone, c] of Object.entries(ch)) {
    let tr = '';
    if (c.x || c.y) tr += `translate(${r2(c.x)}px,${r2(c.y)}px)`;
    if (c.r) tr += `rotate(${r2(c.r)}deg)`;
    if (c.sx || c.sy) tr += `scale(${r2(1 + c.sx)},${r2(1 + c.sy)})`;
    if (!tr) continue;
    const re = new RegExp(`(<g id="${bone}" data-pivot="[^"]+" style="transform-origin:[^"]+)"`);
    if (!re.test(text)) throw new Error('cannot bake ' + bone);
    text = text.replace(re, `$1;transform:${tr}"`);
  }
  return text;
}

if (process.argv[1] === import.meta.filename) {
  const out = bakeDefaults(svg);
  fs.writeFileSync(path.join(OUT, 'character.svg'), out);
  fs.writeFileSync(path.join(OUT, 'rig.json'), JSON.stringify(rig, null, 1) + '\n');
  fs.writeFileSync(path.join(OUT, 'char.bundle.js'),
    '// Generated by src/build.mjs: character.svg and rig.json in one script, so preview.html also opens from disk.\n'
    + `window.CHAR_BUNDLE = ${JSON.stringify({ svg: out, rig })};\n`);
  const shapes = (body.join('\n').match(/<(path|circle|ellipse)\b/g) || []).length;
  const stats = {
    bones: boneList.length, shapes, kb: Math.round(out.length / 1024), joints: rig.joints.length, springs: Object.keys(rig.physics.springs).length,
    rigKb: Math.round(fs.statSync(path.join(OUT, 'rig.js')).size / 1024), vars: Object.keys(PALETTE).length, heads: ((GROUND - 47) / (280 - 47)).toFixed(2),
  };
  fs.writeFileSync(path.join(OUT, 'README.md'), readme(rig, stats));
  console.log(`character.svg ${stats.kb} KB | ${stats.bones} bones | ${stats.shapes} shapes | ${stats.joints} joints | ${stats.springs} springs | ${D.items.size} defs | README.md written`);
}
